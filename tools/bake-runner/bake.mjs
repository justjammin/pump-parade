// Bakes a rigged Meshy GLB into sprite data embedded in ../../index.html: the lifters' RUNNER block or the raccoon's THIEF block.
// Usage: CHROMIUM=<path to a Chromium or chrome-headless-shell binary> node bake.mjs <runner|thief> <model.glb>
import { createServer } from 'node:http';
import { readFileSync, writeFileSync } from 'node:fs';
import { extname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright-core';
import sharp from 'sharp';
import { shapeHands } from './hands.mjs';

const here = fileURLToPath(new URL('.', import.meta.url)), indexPath = join(here, '../../index.html');
const [kind, model] = process.argv.slice(2);
if (!['runner', 'thief'].includes(kind) || !model) throw new Error('usage: node bake.mjs <runner|thief> <model.glb>');
const glb = await shapeHands(readFileSync(model), { fists: kind === 'runner' });

const server = createServer((req, res) => {
  const path = new URL(req.url, 'http://x').pathname;
  if (path === '/model.glb') { res.end(glb); return; }
  const file = path === '/' ? join(here, 'bake.html') : ['/rig.js', '/thief.js'].includes(path) ? join(here, path) : path.startsWith('/three/') ? join(here, 'node_modules', path) : null;
  if (!file) { res.statusCode = 404; res.end(); return; }
  res.setHeader('Content-Type', extname(file) === '.html' ? 'text/html' : 'text/javascript');
  res.end(readFileSync(file));
}).listen(0, '127.0.0.1');
await new Promise(resolve => server.once('listening', resolve));

const browser = await chromium.launch({ executablePath: process.env.CHROMIUM, args: ['--ignore-gpu-blocklist'] });
const page = await browser.newPage();
page.on('pageerror', e => console.error(e));
await page.goto(`http://127.0.0.1:${server.address().port}/`);
await page.waitForFunction(() => window.ready);
const { meta, w, h, rgba } = await page.evaluate(k => window.bake(k), kind);
await browser.close();
server.close();

const raw = Buffer.from(rgba, 'base64'), n = w * h;
let art, sizes;
if (kind === 'runner') {
  // Two images: shade as lossy grey (empty pixels copy their left neighbour so they cost nothing),
  // and class plus coverage as lossless grey+alpha, since a wrong class value would recolour the wrong part.
  const shade = Buffer.alloc(n), cls = Buffer.alloc(n * 2);
  for (let i = 0; i < n; i++) {
    const a = raw[i * 4 + 3];
    shade[i] = a ? raw[i * 4 + 1] : i % w ? shade[i - 1] : 200;
    cls[i * 2] = a ? raw[i * 4] : 0;
    cls[i * 2 + 1] = a;
  }
  const shadeWebp = await sharp(shade, { raw: { width: w, height: h, channels: 1 } }).webp({ quality: 75, effort: 6 }).toBuffer();
  const clsWebp = await sharp(cls, { raw: { width: w, height: h, channels: 2 } }).webp({ lossless: true, effort: 6 }).toBuffer();
  sizes = `shade ${shadeWebp.length} B, parts ${clsWebp.length} B`;
  art = `<script id="runner-art">
// Generated by tools/bake-runner/bake.mjs from a rigged Meshy model. Frames are [x, y, w, h, footX, footY] in sheet pixels.
const RUNNER = {
  scale: ${meta.scale},
  frames: ${JSON.stringify(meta.frames)},
  shade: 'data:image/webp;base64,${shadeWebp.toString('base64')}',
  parts: 'data:image/webp;base64,${clsWebp.toString('base64')}',
};
</script>`;
} else {
  const webp = await sharp(raw, { raw: { width: w, height: h, channels: 4 } }).webp({ quality: 80, alphaQuality: 100, effort: 6 }).toBuffer();
  sizes = `${webp.length} B`;
  art = `<script id="thief-art">
// Generated by tools/bake-runner/bake.mjs from a rigged Meshy model. Frames are [x, y, w, h, footX, footY] in sheet pixels.
const THIEF = {
  scale: ${meta.scale},
  frames: ${JSON.stringify(meta.frames)},
  image: 'data:image/webp;base64,${webp.toString('base64')}',
};
</script>`;
}
const index = readFileSync(indexPath, 'utf8'), block = new RegExp(`<script id="${kind}-art">[\\s\\S]*?</script>`);
if (!block.test(index)) throw new Error(`index.html: expected a <script id="${kind}-art"> block`);
writeFileSync(indexPath, index.replace(block, () => art));
console.log(`Baked ${Object.values(meta.frames).flat().length} frames into a ${w}x${h} sheet: ${sizes}`);
